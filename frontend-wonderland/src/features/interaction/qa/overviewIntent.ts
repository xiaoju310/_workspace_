/** 只识别完整的概览问法，不能把“某个人做了什么事”误当成全页概括。
 * 口头语仅用于意图判断；用户原始转写始终原样显示和留痕。
 */
export type OverviewIntent = 'page' | 'book';
export function overviewIntent(query: string): OverviewIntent | null {
  const text = query.replace(/[\s，,。.!！?？、：:“”"‘’]/g, '')
    .replace(/^(?:嗯|呃|额|唔|啊)+/, '')
    .replace(/^(?:请问|请|能不能|可以|帮我|给我|告诉我|说说|讲讲)+/, '')
    .replace(/(?:呢|吗|呀|啊|吧)+$/, '');
  const scope = '(?:(?:这|那|当前|现在)(?:一)?页(?:书)?|这一段|这段(?:内容)?|这里|(?:这|那)?(?:一|整)?(?:本)?(?:图书|书|绘本)|这个故事|这故事|故事|它|他)';
  const action = '(?:(?:主要|大概)?(?:讲述|讲|说|写)(?:了|的)?(?:是)?(?:一(?:个|件))?(?:什么(?:事(?:情)?|故事|内容)?|啥(?:事|内容)?)|(?:主要)?(?:发生了什么(?:事(?:情)?)?|内容是什么))';
  if (!new RegExp(`^(?:${scope})?(?:它|他)?${action}$`).test(text) &&
      !/^(?:概括|总结)(?:一下)?(?:(?:这|整)?本书|这个故事|这页|这一页|这里|主要内容)?$/.test(text)) return null;
  const pageScope = /^(?:(?:这|那|当前|现在)(?:一)?页|这一段|这段|这里)|(?:概括|总结)(?:一下)?(?:这页|这一页|这里)/.test(text);
  return !pageScope && /图书|绘本|本书|整本|故事|^书/.test(text) ? 'book' : 'page';
}
